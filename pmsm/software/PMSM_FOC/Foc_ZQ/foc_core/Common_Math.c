/* ********************* Butterworth 低通滤波器 ********************* */
void Butterworth_LowPass_Init(BandPassFilter *filter, double cutoff_freq, double sample_freq)
{
    int i;
    double omega_c = 2.0 * My_PI * cutoff_freq;
    double T = 1.0 / sample_freq;
    double pre_warped = tan(omega_c * T / 2.0);
    double K = pre_warped;
    double K2 = K * K;
    double norm = 1.0 + sqrt(2.0) * K + K2;

    filter->b[0] = K2 / norm;
    filter->b[1] = 2.0 * filter->b[0];
    filter->b[2] = filter->b[0];
    filter->a[0] = 1.0;
    filter->a[1] = (2.0 * K2 - 2.0) / norm;
    filter->a[2] = (1.0 - sqrt(2.0) * K + K2) / norm;

    for (i = 0; i < 3; i++) filter->w[i] = 0.0;
}

double Butterworth_LowPass_Update(BandPassFilter *filter, double input)
{
    double output;
    filter->w[0] = input - filter->a[1] * filter->w[1] - filter->a[2] * filter->w[2];
    output = filter->b[0] * filter->w[0] + filter->b[1] * filter->w[1] + filter->b[2] * filter->w[2];
    filter->w[2] = filter->w[1];
    filter->w[1] = filter->w[0];
    return output;
}

/* ********************* Butterworth 带通滤波器 ********************* */
void Butterworth_BandPass_Init(ButterworthBandPassFilter *filter, double center_freq, double Q, double sample_freq)
{
    int i;
    double omega = 2.0 * My_PI * center_freq / sample_freq;
    double alpha = sin(omega) / (2.0 * Q);
    double b0 = alpha, b1 = 0.0, b2 = -alpha;
    double a0 = 1.0 + alpha, a1 = -2.0 * cos(omega), a2 = 1.0 - alpha;

    filter->b[0] = b0 / a0; filter->b[1] = b1 / a0; filter->b[2] = b2 / a0;
    filter->a[0] = a1 / a0; filter->a[1] = a2 / a0;
    for (i = 0; i < 2; i++) { filter->x[i] = 0.0; filter->y[i] = 0.0; }
}

double Butterworth_BandPass_Update(ButterworthBandPassFilter *filter, double input)
{
    double output = filter->b[0] * input + filter->b[1] * filter->x[0] + filter->b[2] * filter->x[1]
                  - filter->a[0] * filter->y[0] - filter->a[1] * filter->y[1];
    filter->x[1] = filter->x[0]; filter->x[0] = input;
    filter->y[1] = filter->y[0]; filter->y[0] = output;
    return output;
}

