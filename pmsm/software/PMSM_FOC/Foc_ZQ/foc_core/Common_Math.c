/* 永磁磁链(Wb): λ_pm = EMF_const / (√3 * 2π * pp * 1000/60)
 *   EMF_const: 反电势常数 VLL_peak/Krpm (线电压峰峰值/(千转/分))
 *   pole_pairs: 极对数
 * 推导: EMF_const[VLL_peak/Krpm], 在 1000RPM 机械转速下 ω_elec = 2π*pp*1000/60 rad/s
 *   V_phase_peak = EMF_const/√3, λ_pm = V_phase_peak/ω_elec */
float CM_CalcFluxLinkage(float emf_const, uint16_t pole_pairs)
{
    float w_elec;
    if (pole_pairs == 0U) return 0.0f;
    w_elec = 2.0f * My_PI * (float)pole_pairs * (1000.0f / 60.0f);
    return (emf_const / 1.7320508f) / w_elec;  /* √3 ≈ 1.73205 */
}

/* 标定用磁链估算: psi = (Vq - Rs*Iq)/we - Ld*Id; 仅计算, 不识别、不更新参数 */
float CM_EstimateFluxLinkage(float vq, float iq, float id, float we, float ld, float rs)
{
    if ((we < 1.0e-6F) && (we > -1.0e-6F)) return 0.0f;
    return ((vq - rs * iq) / we) - (ld * id);
}

/* 电磁转矩(N·m): Te = 1.5 * pp * [λ_pm * Iq + (Ld - Lq) * Id * Iq]
 *   注: 隐极电机(Ld≈Lq)退化为 Te = 1.5 * pp * λ_pm * Iq
 *   各量为标定量纲: Id/Iq[峰值A] Ld/Lq[H] flux[Wb] */
float CM_CalcTorque(float id, float iq, float ld, float lq, float flux_pm, uint16_t pole_pairs)
{
    return 1.5f * (float)pole_pairs * (flux_pm * iq + (ld - lq) * id * iq);
}

/* 电功率(W): Pe = 1.5 * (Vd*Id + Vq*Iq)
 *   Vd/Vq[dq电压峰值V], Id/Iq[dq电流峰值A], 系数 1.5=3/2 来自park变换幅值守恒 */
float CM_CalcElecPower(float vd, float vq, float id, float iq)
{
    return 1.5f * (vd * id + vq * iq);
}

/* 机械功率(W): Pm = Te * ω_mech = Te * 2π * RPM / 60 */
float CM_CalcMechPower(float torque, int32_t speed_rpm)
{
    return torque * 2.0f * My_PI * (float)speed_rpm / 60.0f;
}

/* 母线电流(A): I_bus = Pe / V_bus; 屏蔽 V_bus=0 的除零风险。
   1.12是既有综合校准系数, 只修dq反算口径, 不新增母线采样;
   输出与重构由FOC_MOD_SCALE_MODE同源选择, 不用该系数代替比例切换。 */
#define BUS_CURR_CAL   1.12f
float CM_CalcBusCurrentFromPower(float pe, float v_bus)
{
    if (v_bus < 0.1f) return 0.0f;   /* 母线电压过低时返回 0, 避免除零 */
    return (pe / v_bus) * BUS_CURR_CAL;
}

/* 母线电流(A): 从 dq 电压/电流直接估算 */
float CM_CalcBusCurrent(float vd, float vq, float id, float iq, float v_bus)
{
    return CM_CalcBusCurrentFromPower(CM_CalcElecPower(vd, vq, id, iq), v_bus);
}
