/* (转矩 Nm, 转速 rpm) 双线性查表 -> Id (A) */
float Lookup_Id(float torque, float speed)
{
    int t_idx, s_idx;
    float t_ratio, s_ratio;
    float v0, v1, v2, v3;

    /* 转矩索引(按有效尺寸) */
    if (torque <= Torque_Table[0]) { t_idx = 0; t_ratio = 0.0f; }
    else if (torque >= Torque_Table[g_map_tq_pts-1]) { t_idx = g_map_tq_pts - 2; t_ratio = 1.0f; }
    else { float ts = Torque_Table[1]-Torque_Table[0]; t_idx = (int)((torque-Torque_Table[0])/ts); t_ratio = (torque-Torque_Table[t_idx])/ts; }

    /* 转速索引(按有效尺寸) */
    if (speed <= Speed_Table[0]) { s_idx = 0; s_ratio = 0.0f; }
    else if (speed >= Speed_Table[g_map_spd_pts-1]) { s_idx = g_map_spd_pts - 2; s_ratio = 1.0f; }
    else { float ss = Speed_Table[1]-Speed_Table[0]; s_idx = (int)((speed-Speed_Table[0])/ss); s_ratio = (speed-Speed_Table[s_idx])/ss; }
    /* 越界防护 */
    if(t_idx>g_map_tq_pts-2)
        t_idx=g_map_tq_pts-2;
    else if(t_idx<0)
        t_idx=0;
    if(s_idx>g_map_spd_pts-2)
        s_idx=g_map_spd_pts-2;
    else if(s_idx<0)
        s_idx=0;
    /* 双线性插值 */
    v0 = Id_Map[t_idx][s_idx];
    v1 = Id_Map[t_idx][s_idx+1];
    v2 = Id_Map[t_idx+1][s_idx];
    v3 = Id_Map[t_idx+1][s_idx+1];

    return v0*(1-t_ratio)*(1-s_ratio) + v1*(1-t_ratio)*s_ratio
         + v2*t_ratio*(1-s_ratio)     + v3*t_ratio*s_ratio;
}

