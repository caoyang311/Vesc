/* 标定表运行状态与量程变量 (表本体即上方数组, 上电由 C 初始值装载, 无需初始化调用)
   值表(0x21/02/03)紧致编址: idx = 扭矩行*转速有效点数 + 转速列。 */
uint8_t g_map_rw_status = 0x01U;   /* 0x21/01: 0x01成功 0x02索引超范围 0x03数据超范围 */
uint8_t g_map_tq_pts    = TORQUE_POINTS;   /* MTPA 有效行数(扭矩): 3..32 */
uint8_t g_map_spd_pts   = SPEED_POINTS;    /* MTPA 有效列数(转速): 3..32 */
float   g_map_tq_max    = 50.0F;           /* 扭矩满量程 N.m (0x20/03 idx0) */
float   g_map_spd_max   = 8000.0F;         /* 转速满量程 rpm (0x20/03 idx0) */

/* 值表(0x02/0x03)紧致编址: idx = 扭矩行*当前转速点数 + 转速列 —— 尺寸变化后仍连续;
   底层存储仍按满 32 步长, 这里做 行列->存储位置 换算与有效矩阵边界检查 */
static float *MapStore_Cell(uint8_t sub, uint16_t idx, float *s)
{
    if ((sub == 0x10U) || (sub == 0x11U)) {
        uint16_t r_ = (uint16_t)(idx / g_map_ld_iq_pts);
        uint16_t c_ = (uint16_t)(idx % g_map_ld_iq_pts);
        if ((r_ >= g_map_ld_id_pts) || (c_ >= g_map_ld_iq_pts)) { return 0; }
        return &s[(uint16_t)((uint16_t)r_ * LD_SAT_IQ_PTS) + c_];
    }
    if ((sub == 0x02U) || (sub == 0x03U)) {
        uint16_t r_ = (uint16_t)(idx / g_map_spd_pts);
        uint16_t c_ = (uint16_t)(idx % g_map_spd_pts);
        if ((r_ >= g_map_tq_pts) || (c_ >= g_map_spd_pts)) { return 0; }
        return &s[(uint16_t)((uint16_t)r_ * SPEED_POINTS) + c_];
    }
    return &s[idx];
}

/* 标定表读写 (协议 0x21): sub 与数组编号对齐; 索引=数组下标, 越界/非法值返回状态码。
   返回: 0x01 成功 / 0x02 索引超范围 / 0x03 写入数据超范围。 */
static float *MapStore_Slot(uint8_t sub, uint16_t idx, uint16_t *limit)
{
    *limit = 0U;
    switch (sub) {
    case 0x02U: *limit = (uint16_t)g_map_tq_pts * g_map_spd_pts; return &Id_Map[0][0];   /* MTPA-D轴电流参考(紧致) */
    case 0x03U: *limit = (uint16_t)g_map_tq_pts * g_map_spd_pts; return &Iq_Map[0][0];   /* MTPA-Q轴电流参考(紧致) */
    case 0x04U: *limit = g_map_spd_pts;  return &Speed_Table[0];  /* X轴: 转速(有效长度) */
    case 0x05U: *limit = g_map_tq_pts;  return &Torque_Table[0]; /* Y轴: 扭矩(有效长度) */
    case 0x06U: *limit = g_map_rs_pts;  return &Rs_Temp_Table[0];   /* Temp(Rs) */
    case 0x07U: *limit = g_map_rs_pts;  return &Rs_Value_Table[0];    /* Rs 值 */
    case 0x08U: *limit = g_map_psi_pts; return &Psi_Temp_Table[0];  /* Temp(Phi) */
    case 0x09U: *limit = g_map_psi_pts; return &Psi_Value_Table[0];   /* Phi 值 */
    case 0x10U: *limit = (uint16_t)g_map_ld_id_pts * g_map_ld_iq_pts; return &Ld_Sat_Map[0][0];   /* Ld 值表 */
    case 0x11U: *limit = (uint16_t)g_map_ld_id_pts * g_map_ld_iq_pts; return &Lq_Sat_Map[0][0];   /* Lq 值表 */
    case 0x12U: *limit = g_map_ld_id_pts; return &Ld_Id_Axis[0];  /* Ld/Lq 表-D轴(Id)参考 */
    case 0x13U: *limit = g_map_ld_iq_pts; return &Ld_Iq_Axis[0];  /* Ld/Lq 表-Q轴(Iq)参考 */
    default: return 0;
    }
}

/* 前置声明: 定义在本文件末尾(轴保护辅助) */
static uint8_t MapStore_IsAxisSub(uint8_t sub);
static uint8_t MapStore_AxisOK(const float *a, uint16_t n);

uint8_t MapStore_Read(uint8_t sub, uint16_t idx, float *v)
{
    uint16_t lim;
    float *s = MapStore_Slot(sub, idx, &lim);
    float *e;
    if ((s == 0) || (idx >= lim) || (v == 0)) { g_map_rw_status = 0x02U; return 0U; }
    e = MapStore_Cell(sub, idx, s);
    if (e == 0) { g_map_rw_status = 0x02U; return 0U; }   /* 值表越出有效矩阵 */
    *v = *e;
    g_map_rw_status = 0x01U;
    return 1U;
}

uint8_t MapStore_Write(uint8_t sub, uint16_t idx, float v)
{
    uint16_t lim;
    float *s = MapStore_Slot(sub, idx, &lim);
    float *e;
    if ((s == 0) || (idx >= lim)) { g_map_rw_status = 0x02U; return 0U; }
    if (!(v >= -1.0e6F) || !(v <= 1.0e6F)) { g_map_rw_status = 0x03U; return 0U; }  /* 含 NaN */
    e = MapStore_Cell(sub, idx, s);
    if (e == 0) { g_map_rw_status = 0x02U; return 0U; }   /* 值表越出有效矩阵 */
    if (MapStore_IsAxisSub(sub) != 0U) {
        float old = *e;
        *e = v;
        {   /* 轴长度 = 本次可写元素个数 */
            uint16_t n = lim;
            if (MapStore_AxisOK(s, n) == 0U) {
                *e = old;                       /* 破坏等间隔: 回滚 */
                g_map_rw_status = 0x03U;
                return 0U;
            }
        }
    } else {
        *e = v;
    }
    g_map_rw_status = 0x01U;
    /* 注意: 这里**不得**重算轴向表 —— 否则写完轴向值再写任一表格元素, 轴向会被覆盖回等间隔
       默认值(上位机表现为"改了这个那个又复原")。轴向重算只在显式写"间隔"(协议 0x20/03
       idx0/idx1) 时由 canopen 侧调用 MapStore_RebuildAxis()。 */
    return 1U;
}

/* 矩阵信息 (协议 0x20/03): 间隔(N.m / 1rpm) -> 等间隔轴向表; 最大值由 (点数-1)*间隔 派生 */
float g_map_torque_step = 1.612903F;   /* 扭矩间隔 N.m (0x20/03 idx1 只读) = 50/31 */
float g_map_speed_step  = 258.064516F; /* 转速间隔 rpm (0x20/03 idx1 只读) = 8000/31 */
void MapStore_RebuildAxis(void)
{
    uint16_t i;
    if (g_map_torque_step <= 0.0F) {
        g_map_torque_step = (TORQUE_POINTS > 1U) ? (g_map_tq_max / (float)(TORQUE_POINTS-1)) : 1.0F;
    }
    if (g_map_speed_step <= 0.0F) {
        g_map_speed_step = (SPEED_POINTS > 1U) ? (g_map_spd_max / (float)(SPEED_POINTS-1)) : 1.0F;
    }
    for (i = 0U; i < TORQUE_POINTS; i++) { Torque_Table[i] = (float)i * g_map_torque_step; }
    for (i = 0U; i < SPEED_POINTS;  i++) { Speed_Table[i]  = (float)i * g_map_speed_step;  }
}

/* 设置 MTPA 有效尺寸(3..32): 保住当前量程不变, 间隔按新点数重排后重建等间隔轴。
   越出有效矩阵的数据不清除(镜像仍按满 32 存), 尺寸放大后原数据自动回到有效区 */
uint8_t MapStore_SetSize(uint8_t tq_pts, uint8_t spd_pts)
{
    float tmax, smax;
    if ((tq_pts < 3U) || (tq_pts > (uint8_t)TORQUE_POINTS) ||
        (spd_pts < 3U) || (spd_pts > (uint8_t)SPEED_POINTS)) {
        g_map_rw_status = 0x02U;
        return 0U;
    }


    tmax = g_map_tq_max;
    smax = g_map_spd_max;
    g_map_tq_pts  = tq_pts;
    g_map_spd_pts = spd_pts;
    g_map_torque_step = tmax / (float)(tq_pts - 1U);
    g_map_speed_step  = smax / (float)(spd_pts - 1U);
    MapStore_RebuildAxis();
    g_map_rw_status = 0x01U;
    return 1U;
}

/* Rs/磁链温度表有效点数(3..10)与 Ld/Lq 饱和表有效尺寸(3..6 x 3..6, 两表共用轴):
   只改读写窗口, 轴与数据不动, 上电回满 */
uint8_t g_map_rs_pts   = RS_TEMP_POINTS;
uint8_t g_map_psi_pts  = PSI_TEMP_POINTS;
uint8_t g_map_ld_id_pts = LD_SAT_ID_PTS;
uint8_t g_map_ld_iq_pts = LD_SAT_IQ_PTS;

uint8_t MapStore_SetAuxSize(uint8_t rs_pts, uint8_t psi_pts)
{
    if ((rs_pts < 3U) || (rs_pts > (uint8_t)RS_TEMP_POINTS) ||
        (psi_pts < 3U) || (psi_pts > (uint8_t)PSI_TEMP_POINTS)) {
        g_map_rw_status = 0x02U;
        return 0U;
    }
    {   /* 先按旧有效窗口取量程, 再改尺寸重排温度轴(与 MTPA SetSize 同口径) */
        float r0 = Rs_Temp_Table[0];
        float r1 = Rs_Temp_Table[g_map_rs_pts - 1U];
        float p0 = Psi_Temp_Table[0];
        float p1 = Psi_Temp_Table[g_map_psi_pts - 1U];
        int i;
        float sr = (r1 - r0) / (float)(rs_pts - 1U);
        float sp = (p1 - p0) / (float)(psi_pts - 1U);
        for (i = 0; i < RS_TEMP_POINTS; i++)  { Rs_Temp_Table[i]  = r0 + (float)i * sr; }
        for (i = 0; i < PSI_TEMP_POINTS; i++) { Psi_Temp_Table[i] = p0 + (float)i * sp; }
    }
    g_map_rs_pts  = rs_pts;
    g_map_psi_pts = psi_pts;

    g_map_rw_status = 0x01U;
    return 1U;
}

uint8_t MapStore_SetLdSize(uint8_t id_pts, uint8_t iq_pts)
{
    if ((id_pts < 3U) || (id_pts > (uint8_t)LD_SAT_ID_PTS) ||
        (iq_pts < 3U) || (iq_pts > (uint8_t)LD_SAT_IQ_PTS)) {
        g_map_rw_status = 0x02U;
        return 0U;
    }
    {   /* 先按旧有效窗口取量程, 再改尺寸重排轴(Id: -量程..0, Iq: 0..量程, N-1 等分) */
        float id_top = -Ld_Id_Axis[0];
        float iq_top = Ld_Iq_Axis[g_map_ld_iq_pts - 1U];
        float si = id_top / (float)(id_pts - 1U);
        float sq = iq_top / (float)(iq_pts - 1U);
        int i;
        for (i = 0; i < LD_SAT_ID_PTS; i++) {
            Ld_Id_Axis[i] = (i < (int)(id_pts - 1U)) ? (-((float)(id_pts - 1U - i) * si)) : 0.0F;
            Lq_Id_Axis[i] = Ld_Id_Axis[i];
        }
        for (i = 0; i < LD_SAT_IQ_PTS; i++) {
            Ld_Iq_Axis[i] = (float)i * sq;
            Lq_Iq_Axis[i] = Ld_Iq_Axis[i];
        }
    }
    g_map_ld_id_pts = id_pts;
    g_map_ld_iq_pts = iq_pts;
    g_map_rw_status = 0x01U;
    return 1U;
}

/* 轴向表写保护: 查表按"等间隔"算下标(step = 轴[1]-轴[0]), 轴被写成非等间隔会让索引算错。
   故轴向表的写入必须保持"严格递增且步长一致", 否则回滚并置状态 0x03。 */
static uint8_t MapStore_IsAxisSub(uint8_t sub)
{
    return ((sub == 0x04U) || (sub == 0x05U) ||   /* MTPA X轴(转速) / Y轴(扭矩) */
            (sub == 0x06U) || (sub == 0x08U) ||   /* Temp(Rs) / Temp(Phi) */
            (sub == 0x0CU) || (sub == 0x0DU)) ? 1U : 0U;   /* Ld/Lq 表 D/Q 轴 */
}

static uint8_t MapStore_AxisOK(const float *a, uint16_t n)
{
    uint16_t i;
    float d0, d;
    if ((a == 0) || (n < 2U)) { return 1U; }
    d0 = a[1] - a[0];
    if (!(d0 > 0.0F)) { return 0U; }            /* 必须递增 */
    for (i = 1U; i + 1U < n; i++) {
        d = a[i + 1U] - a[i];
        if (!(d > 0.0F)) { return 0U; }
        if (((d > d0) ? (d - d0) : (d0 - d)) > (d0 * 1.0e-3F)) { return 0U; }   /* 步长一致 */
    }
    return 1U;
}

/* Ld/Lq 饱和表 2D 双线性查表 (uH)。轴向表等间隔(120A), 索引按区间定位,
   轴外值钳位到边界点。Id 轴 [-600..0]A, Iq 轴 [0..600]A;
   制动 Id>0 超出 Id 轴 -> 钳到 0A 列 (=不饱和标称值), 合理回退。 */
static int Map_AxisIdx(float v, const float *axis, int n, float *ratio)
{
    float step = axis[1] - axis[0];
    float f;
    int   idx;

    if (!(step > 0.0F)) { *ratio = 0.0F; return 0; }   /* 含 step=NaN 防护 */
    f = (v - axis[0]) / step;
    if (!(f > 0.0F))              { idx = 0;     *ratio = 0.0F; }
    else if (f >= (float)(n - 1)) { idx = n - 2; *ratio = 1.0F; }
    else                          { idx = (int)f; *ratio = f - (float)idx; }
    return idx;
}

float Lookup_Ld(float id_a, float iq_a)
{
    float ri, rj;
    int   i, j;
    float v0, v1, v2, v3;

    i = Map_AxisIdx(id_a, Ld_Id_Axis, g_map_ld_id_pts, &ri);
    j = Map_AxisIdx(iq_a, Ld_Iq_Axis, g_map_ld_iq_pts, &rj);
    v0 = Ld_Sat_Map[i][j];     v1 = Ld_Sat_Map[i][j + 1];
    v2 = Ld_Sat_Map[i + 1][j]; v3 = Ld_Sat_Map[i + 1][j + 1];
    return v0 * (1.0F - ri) * (1.0F - rj) + v1 * (1.0F - ri) * rj
         + v2 * ri * (1.0F - rj)         + v3 * ri * rj;
}

float Lookup_Lq(float id_a, float iq_a)
{
    float ri, rj;
    int   i, j;
    float v0, v1, v2, v3;

    i = Map_AxisIdx(id_a, Lq_Id_Axis, g_map_ld_id_pts, &ri);
    j = Map_AxisIdx(iq_a, Lq_Iq_Axis, g_map_ld_iq_pts, &rj);
    v0 = Lq_Sat_Map[i][j];     v1 = Lq_Sat_Map[i][j + 1];
    v2 = Lq_Sat_Map[i + 1][j]; v3 = Lq_Sat_Map[i + 1][j + 1];
    return v0 * (1.0F - ri) * (1.0F - rj) + v1 * (1.0F - ri) * rj
         + v2 * ri * (1.0F - rj)         + v3 * ri * rj;
}
