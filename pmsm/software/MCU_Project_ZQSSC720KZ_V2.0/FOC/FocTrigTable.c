/**
 * @brief 对第一象限等效相位执行查表和线性插值。
 *
 * @param[in] table_phase 第一象限等效相位，范围为0至0x4000。
 *
 * @return 对应的正弦绝对值，范围为0.0F至1.0F。
 */
static float FocTrig_Interpolate(uint16_t table_phase)
{
    uint16_t index = (uint16_t)(table_phase >> FOC_TRIG_INDEX_SHIFT);
    uint16_t fraction = (uint16_t)(table_phase & FOC_TRIG_INDEX_MASK);
    float value = 0.0F;
    float next_value = 0.0F;

    value = FocTrig_SineTable[index];

    if (index < FOC_TRIG_LAST_INDEX)
    {
        next_value = FocTrig_SineTable[(uint16_t)(index + 1U)];
        value += (next_value - value) *
                 ((float)fraction * FOC_TRIG_INTERPOLATION_SCALE);
    }
    else
    {
        /* 第一象限端点直接使用表中最大索引值。 */
    }

    return value;
}

/**
 * @brief 根据相位提取第一象限等效相位和符号。
 *
 * @param[in] phase 完整电周期相位。
 * @param[out] table_phase 第一象限等效相位，指针不得为NULL。
 * @param[out] sign 正弦符号，返回1.0F或-1.0F，指针不得为NULL。
 *
 * @note 输出指针由本文件内部调用方保证有效。
 */
static void FocTrig_MapPhase(uint16_t phase,
                             uint16_t * table_phase,
                             float * sign)
{
    uint16_t quadrant = (uint16_t)(phase >> 14U);
    uint16_t offset = (uint16_t)(phase & UINT16_C(0x3FFF));

    if ((quadrant == 1U) || (quadrant == 3U))
    {
        *table_phase = (uint16_t)(FOC_TRIG_QUARTER_PHASE - offset);
    }
    else
    {
        *table_phase = offset;
    }

    if (quadrant >= 2U)
    {
        *sign = -1.0F;
    }
    else
    {
        *sign = 1.0F;
    }
}

/**
 * @brief 根据完整电周期相位获取正弦和余弦值。
 *
 * 采用一次公共相位解析，同时对正弦和余弦执行象限映射、查表和线性插值。
 * 余弦使用相位加四分之一周期后的等效第一象限相位，不重复调用完整查表路径。
 *
 * @param[in] phase 完整电周期相位，0x0000至0xFFFF。
 * @param[out] trig 输出结构体指针；为NULL时不执行写操作。
 *
 * @return None.
 */
void FocTrig_GetSinCos(uint16_t phase, Foc_TrigType * trig)
{
    Foc_TrigType result = {0};
    uint16_t sine_phase = 0U;
    uint16_t cosine_phase = 0U;
    uint16_t cosine_table_phase = 0U;
    float sine_sign = 1.0F;
    float cosine_sign = 1.0F;

    cosine_phase = (uint16_t)(phase + FOC_TRIG_QUARTER_PHASE);
    FocTrig_MapPhase(phase, &sine_phase, &sine_sign);
    FocTrig_MapPhase(cosine_phase,
                        &cosine_table_phase,
                        &cosine_sign);

    result.sine = sine_sign * FocTrig_Interpolate(sine_phase);
    result.cosine = cosine_sign * FocTrig_Interpolate(cosine_table_phase);
    *trig = result;
}
